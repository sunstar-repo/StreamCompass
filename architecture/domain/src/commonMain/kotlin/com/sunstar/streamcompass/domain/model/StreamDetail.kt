package com.sunstar.streamcompass.domain.model

sealed interface StreamDetail {
    data class MovieStreamDetail(
        val tmdbId: Int,
        val title: String,
        val overview: String,
        val posterPath: String,
        val backdropPath: String,
        val releaseDate: String,
        val voteAverage: Double,
        val voteCount: Int,
        val popularity: Double,
        val originalLanguage: String,
        val originalTitle: String,
        val genres: List<String>,
        val runtime: Int,
        val status: String,
        val tagline: String,
        val homepage: String,
        val imdbId: String,
        val budget: Long,
        val revenue: Long,
        val adult: Boolean,
        val video: Boolean,
        val logo: String,
        val backdrops: List<String>,
        val posters: List<String>,
        val certification: String,
        val productionCompanyLogo: String,
        val trailerKeys: List<String>,
        val cast: List<Person>,
        val crew: List<Person>,
        val deeplinks: List<Deeplink>,
    ) : StreamDetail

    data class TvStreamDetail(
        val tmdbId: Int,
        val name: String,
        val overview: String,
        val posterPath: String,
        val backdropPath: String,
        val firstAirDate: String,
        val lastAirDate: String,
        val voteAverage: Double,
        val voteCount: Int,
        val popularity: Double,
        val originalLanguage: String,
        val originalName: String,
        val genres: List<String>,
        val numberOfSeasons: Int,
        val numberOfEpisodes: Int,
        val episodeRunTime: List<Int>,
        val status: String,
        val tagline: String,
        val homepage: String,
        val inProduction: Boolean,
        val logo: String,
        val backdrops: List<String>,
        val posters: List<String>,
        val certification: String,
        val networkLogo: String,
        val trailerKeys: List<String>,
        val cast: List<Person>,
        val crew: List<Person>,
        val deeplinks: List<Deeplink>,
    ) : StreamDetail
}
